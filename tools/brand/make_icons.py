"""Builds GUDORY's launcher icons and in-app logo from docs/brand/logo.svg.

No SVG library needed: the logo only uses absolute M/C/L/H/V/Z commands, so
the paths are flattened here and filled with PIL (nonzero, 4x supersampled).

    python tools/brand/make_icons.py

Writes:
  app/android/app/src/main/res/mipmap-*/ic_launcher.png      legacy (API 24-25)
  app/android/app/src/main/res/drawable/ic_launcher_foreground.xml  adaptive (26+)
  app/assets/brand/logo_on_dark.png                           in-app wordmark
"""
import re
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
SVG = ROOT / "docs/brand/logo.svg"
RES = ROOT / "app/android/app/src/main/res"
YELLOW = (0xFB, 0xBC, 0x00, 255)
SS = 4  # supersampling


def parse_paths(svg):
    return re.findall(r'<path d="([^"]+)" fill="([^"]+)"', svg)


def subpaths(d, steps=24):
    """Flattened closed polygons of an absolute-command path."""
    tokens = re.findall(r"[MCLHVZ]|-?\d*\.?\d+(?:e-?\d+)?", d)
    polys, cur, pos, i, cmd = [], [], (0.0, 0.0), 0, None
    while i < len(tokens):
        t = tokens[i]
        if t.isalpha():
            cmd = t
            i += 1
            if cmd == "Z":
                if cur:
                    polys.append(cur)
                cur = []
            continue
        nums = lambda n: [float(x) for x in tokens[i:i + n]]
        if cmd == "M":
            pos = tuple(nums(2)); cur = [pos]; i += 2; cmd = "L"
        elif cmd == "L":
            pos = tuple(nums(2)); cur.append(pos); i += 2
        elif cmd == "H":
            pos = (nums(1)[0], pos[1]); cur.append(pos); i += 1
        elif cmd == "V":
            pos = (pos[0], nums(1)[0]); cur.append(pos); i += 1
        elif cmd == "C":
            x1, y1, x2, y2, x, y = nums(6)
            x0, y0 = pos
            for s in range(1, steps + 1):
                u = s / steps
                a, b, c, e = (1 - u) ** 3, 3 * (1 - u) ** 2 * u, 3 * (1 - u) * u * u, u ** 3
                cur.append((a * x0 + b * x1 + c * x2 + e * x, a * y0 + b * y1 + c * y2 + e * y))
            pos = (x, y); i += 6
        else:
            raise ValueError(f"unsupported command {cmd}")
    if cur:
        polys.append(cur)
    return polys


def mask(d, scale, offset, size):
    """Nonzero-winding coverage mask of path [d] (SVG's default fill rule;
    the letters self-overlap, so even-odd would punch holes)."""
    w, h = size[0] * SS, size[1] * SS
    edges = []
    for poly in subpaths(d):
        pts = [((x * scale + offset[0]) * SS, (y * scale + offset[1]) * SS) for x, y in poly]
        for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]):
            if y0 != y1:
                edges.append((x0, y0, x1, y1))
    m = Image.new("L", (w, h), 0)
    draw = ImageDraw.Draw(m)
    for row in range(h):
        y = row + 0.5
        hits = []
        for x0, y0, x1, y1 in edges:
            if (y0 <= y < y1) or (y1 <= y < y0):
                hits.append((x0 + (y - y0) * (x1 - x0) / (y1 - y0), 1 if y1 > y0 else -1))
        hits.sort()
        winding = 0
        for (xa, da), (xb, _) in zip(hits, hits[1:]):
            winding += da
            if winding != 0:
                draw.line([(round(xa), row), (round(xb) - 1, row)], fill=255)
    return m.resize(size, Image.LANCZOS)


def paint(img, d, color, scale, offset):
    solid = Image.new("RGBA", img.size, color)
    img.alpha_composite(Image.composite(solid, Image.new("RGBA", img.size, (0, 0, 0, 0)),
                                        mask(d, scale, offset, img.size)))


def main():
    paths = parse_paths(SVG.read_text(encoding="utf-8"))
    g = paths[-1][0]  # the yellow "G"
    g_w, g_h = 100.238, 125.235

    # Legacy launcher icons: black rounded square, yellow G.
    for name, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        img = Image.new("RGBA", (px, px), (0, 0, 0, 0))
        bg = Image.new("L", (px * SS, px * SS), 0)
        ImageDraw.Draw(bg).rounded_rectangle([0, 0, px * SS - 1, px * SS - 1], radius=px * SS * 0.22, fill=255)
        img.paste((0, 0, 0, 255), (0, 0), bg.resize((px, px), Image.LANCZOS))
        scale = px * 0.56 / g_h
        paint(img, g, YELLOW, scale, ((px - g_w * scale) / 2, (px - g_h * scale) / 2))
        img.save(RES / f"mipmap-{name}/ic_launcher.png")

    # Adaptive foreground (108 dp canvas, 66 dp safe zone): same G as a vector.
    scale = 50 / g_h
    tx, ty = (108 - g_w * scale) / 2, (108 - g_h * scale) / 2
    (RES / "drawable/ic_launcher_foreground.xml").write_text(
        f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/brand/make_icons.py from docs/brand/logo.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:translateX="{tx:.3f}"
        android:translateY="{ty:.3f}"
        android:scaleX="{scale:.5f}"
        android:scaleY="{scale:.5f}">
        <path
            android:fillColor="#FBBC00"
            android:pathData="{g}" />
    </group>
</vector>
""", encoding="utf-8")

    # In-app wordmark for dark backgrounds: the black letters become white.
    scale = 2.0
    out = Image.new("RGBA", (int(696 * scale), int(126 * scale)), (0, 0, 0, 0))
    for d, fill in paths:
        color = (255, 255, 255, 255) if fill == "black" else YELLOW
        paint(out, d, color, scale, (0, 0))
    dest = ROOT / "app/assets/brand/logo_on_dark.png"
    dest.parent.mkdir(parents=True, exist_ok=True)
    out.save(dest)
    print("icons + logo written")


if __name__ == "__main__":
    main()
